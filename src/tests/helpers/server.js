const CLIENT_IP = '203.0.113.7';

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function createClock(start = Date.UTC(2026, 0, 15, 12, 0, 0)) {
  let current = start;
  return {
    now: () => current,
    advance(ms) {
      current += ms;
    },
  };
}

// Where each URL is handled. Requires run lazily, so they always see the modules of the current test.
const ROUTES = [
  { pattern: /^\/api\/auth\/login$/, load: () => require('../../app/api/auth/login/route') },
  { pattern: /^\/api\/auth\/logout$/, load: () => require('../../app/api/auth/logout/route') },
  { pattern: /^\/api\/products$/, load: () => require('../../app/api/products/route') },
  { pattern: /^\/api\/orders$/, load: () => require('../../app/api/orders/route') },
  { pattern: /^\/api\/orders\/([^/]+)$/, params: ['id'], load: () => require('../../app/api/orders/[id]/route') },
  { pattern: /^\/api\/checkout$/, load: () => require('../../app/api/checkout/route') },
];

async function toResult(response) {
  const text = await response.text();
  let body = {};
  try {
    body = text ? JSON.parse(text) : {};
  } catch {
    body = {};
  }
  const headers = {};
  response.headers.forEach((value, name) => {
    headers[name.toLowerCase()] = value;
  });
  return { status: response.status, headers, body, text };
}

const emptyResult = (status) => ({ status, headers: {}, body: {}, text: '' });

// A request that is sent when awaited: `await api.post('/api/x').set('A', 'b').send({ ... })`.
class ApiRequest {
  constructor(method, path) {
    this.method = method;
    this.path = path;
    this.headers = { 'x-forwarded-for': CLIENT_IP };
    this.payload = undefined;
  }

  set(name, value) {
    this.headers[name.toLowerCase()] = value;
    return this;
  }

  send(body) {
    this.payload = body;
    return this;
  }

  then(onFulfilled, onRejected) {
    return this.execute().then(onFulfilled, onRejected);
  }

  async execute() {
    const url = new URL(this.path, 'http://localhost:3000');
    const route = ROUTES.find((candidate) => candidate.pattern.test(url.pathname));
    if (!route) return emptyResult(404);

    const match = route.pattern.exec(url.pathname);
    const params = Object.fromEntries((route.params || []).map((name, i) => [name, decodeURIComponent(match[i + 1])]));
    const init = { method: this.method, headers: { ...this.headers } };
    if (this.payload !== undefined) {
      init.body = JSON.stringify(this.payload);
      init.headers['content-type'] = 'application/json';
    }

    const handler = route.load()[this.method];
    if (typeof handler !== 'function') return emptyResult(405);

    try {
      const request = new NextRequest(url.href, init);
      const response = await currentRequest.run(request, () => handler(request, { params }));
      return await toResult(response);
    } catch (err) {
      // Next.js answers an error that escapes a route handler with a 500.
      console.error(err);
      return emptyResult(500);
    }
  }
}

/**
 * Builds a fresh server context from freshly loaded modules, so no state leaks between tests.
 * Pass `db` to reuse a database (simulates a server restart).
 */
async function setup({ db, delayMs = 0, decline = false } = {}) {
  jest.resetModules();
  const { createDatabase } = require('../../server/db');
  const { createContext, setContext } = require('../../server/context');
  const { PaymentDeclinedError } = require('../../server/payments');

  const payments = {
    decline,
    delayMs,
    charge: jest.fn(async ({ amountCents }) => {
      await sleep(payments.delayMs);
      if (payments.decline) throw new PaymentDeclinedError();
      return { id: `ch_test_${payments.charge.mock.calls.length}`, amountCents, status: 'succeeded' };
    }),
  };

  const clock = createClock();
  const database = db || (await createDatabase());
  setContext(createContext({ db: database, payments, now: clock.now }));
  return {
    db: database,
    payments,
    clock,
    api: () => ({
      get: (path) => new ApiRequest('GET', path),
      post: (path) => new ApiRequest('POST', path),
    }),
  };
}

async function login(ctx, email = USERS[0], password = PASSWORD) {
  const res = await ctx.api().post('/api/auth/login').send({ email, password });
  if (res.status !== 200 || !res.body.token) {
    throw new Error(`Login failed for ${email}: ${res.status} ${JSON.stringify(res.body)}`);
  }
  return res.body.token;
}

function checkout(ctx, token, items, key) {
  const req = ctx.api().post('/api/checkout').set('Authorization', `Bearer ${token}`);
  if (key !== undefined) req.set('Idempotency-Key', key);
  return req.send({ items });
}

function get(ctx, path, token) {
  const req = ctx.api().get(path);
  if (token) req.set('Authorization', `Bearer ${token}`);
  return req;
}

async function count(ctx, table) {
  const row = await ctx.db.get(`SELECT COUNT(*) AS n FROM ${table}`);
  return row.n;
}

async function counts(ctx) {
  return {
    orders: await count(ctx, 'orders'),
    orderItems: await count(ctx, 'order_items'),
    invoices: await count(ctx, 'invoices'),
    emails: await count(ctx, 'emails'),
  };
}

async function stockOf(ctx, productId) {
  const row = await ctx.db.get('SELECT stock FROM products WHERE id = ?', [productId]);
  return row.stock;
}

async function setStock(ctx, productId, stock) {
  await ctx.db.run('UPDATE products SET stock = ? WHERE id = ?', [stock, productId]);
}

async function userId(ctx, email) {
  const row = await ctx.db.get('SELECT id FROM users WHERE email = ?', [email]);
  return row.id;
}

// Inserts `n` orders for a user directly, oldest first, one minute apart. Returns ids oldest first.
async function insertOrders(ctx, email, n) {
  const uid = await userId(ctx, email);
  const base = ctx.clock.now() - n * 60 * 1000;
  const ids = [];
  for (let i = 0; i < n; i += 1) {
    const { lastInsertRowid } = await ctx.db.run(
      "INSERT INTO orders (user_id, status, total_cents, created_at) VALUES (?, 'paid', ?, ?)",
      [uid, 1000 + i, base + i * 60 * 1000]
    );
    ids.push(lastInsertRowid);
  }
  return ids;
}

