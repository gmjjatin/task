const USER = { id: 1, email: 'alice@shoplite.test', name: 'Alice' };

function jsonResponse(status, body, headers = {}) {
  const lower = Object.fromEntries(Object.entries(headers).map(([k, v]) => [k.toLowerCase(), String(v)]));
  return {
    ok: status >= 200 && status < 300,
    status,
    statusText: String(status),
    headers: { get: (name) => (name.toLowerCase() in lower ? lower[name.toLowerCase()] : null) },
    json: async () => body,
    text: async () => JSON.stringify(body),
    clone() {
      return this;
    },
  };
}

function deferred() {
  let resolve;
  let reject;
  const promise = new Promise((res, rej) => {
    resolve = res;
    reject = rej;
  });
  return { promise, resolve, reject };
}

function pathOf(url) {
  return new URL(String(url), 'http://localhost').pathname;
}

function headerOf(init, name) {
  const headers = (init && init.headers) || {};
  if (typeof headers.get === 'function') return headers.get(name);
  const match = Object.keys(headers).find((key) => key.toLowerCase() === name.toLowerCase());
  return match ? headers[match] : undefined;
}

/**
 * Installs a fake fetch. `handlers` maps "METHOD /path" to a function (url, init) => response | Promise.
 * Login and products have defaults.
 */
function mockApi(handlers = {}) {
  const routes = {
    'POST /api/auth/login': () => jsonResponse(200, { token: 'a'.repeat(64), user: USER }),
    'GET /api/products': () => jsonResponse(200, { items: PRODUCTS }),
    'GET /api/orders': () => jsonResponse(200, { items: [], page: 1, limit: 10, total: 0 }),
    ...handlers,
  };
  const fetchMock = jest.fn(async (url, init = {}) => {
    const route = `${(init.method || 'GET').toUpperCase()} ${pathOf(url)}`;
    const handler = routes[route];
    if (!handler) return jsonResponse(404, { error: { code: 'NOT_FOUND', message: `No mock for ${route}` } });
    return handler(url, init);
  });
  global.fetch = fetchMock;
  window.fetch = fetchMock;
  return fetchMock;
}

function callsTo(fetchMock, method, path) {
  return fetchMock.mock.calls.filter(
    ([url, init = {}]) => (init.method || 'GET').toUpperCase() === method && pathOf(url) === path
  );
}

function renderApp() {
  const App = require('../../client/App').default;
  const user = userEvent.setup();
  const utils = render(<App />);
  return { user, ...utils };
}

async function logIn(user, email = USER.email, password = 'password123') {
  await user.type(screen.getByLabelText(/email/i), email);
  await user.type(screen.getByLabelText(/password/i), password);
  await user.click(screen.getByRole('button', { name: /log in/i }));
}

// Renders the app, logs in through the form, and waits for the product list.
async function renderLoggedIn() {
  const utils = renderApp();
  await logIn(utils.user);
  await screen.findByRole('list', { name: /products/i });
  await within(screen.getByRole('list', { name: /products/i })).findAllByRole('listitem');
  return utils;
}

function productItem(name) {
  const items = within(screen.getByRole('list', { name: /products/i })).getAllByRole('listitem');
  const item = items.find((li) => within(li).queryByText(name));
  if (!item) throw new Error(`Product "${name}" is not visible`);
  return item;
}

async function addToCart(user, name) {
  await user.click(within(productItem(name)).getByRole('button', { name: /add to cart/i }));
}

function placeOrderButton() {
  return screen.getByRole('button', { name: /place order/i });
}

async function expectAlert(...patterns) {
  await waitFor(() => {
    const alerts = screen.queryAllByRole('alert');
    const match = alerts.some((alert) => patterns.every((p) => p.test(alert.textContent)));
    expect(match).toBe(true);
  });
}

